/**
 * MD5 字面量的唯一出处（P3-3，第四批）。
 *
 * ## 为什么要有这个文件
 *
 * `^[0-9a-f]{32}$` 这串正则在 `query/**` 里散落过 10 处，而它们**并不完全同义**：
 * 有的带 `i`、有的不带；有的是「整串校验」、有的是「从一段二进制里抽第一个 32 位十六进制」；
 * 有的拼在 `^(...)(\.t)?\.dat$` 这种更大的模式里。散落的后果不是「重复」这么轻 ——
 * 下次有人改其中一处（比如放宽大小写）时，另外九处静默保持旧口径，
 * 于是同一张图在「按 md5 找缓存」和「按 md5 记账」两条路上被当成两个不同的东西。
 *
 * ## 两种校验为什么都留着
 *
 * 这是**刻意不统一**的：`isMd5` 只认小写（历史上多数站点就是这个口径，收紧会误拒、
 * 放宽会误命中缓存文件名），`isMd5Loose` 认大小写两种（给「从用户可见文本里找」的那两处用）。
 * 两者的差别必须写在名字里，而不是散落在 10 个正则字面量里靠某个作者记不记得加 `i`。
 */

/** 单个 32 位十六进制段的字面量（供拼进更大的模式）。 */
export const MD5_SEGMENT = '[0-9a-f]{32}'

/** 整串校验：32 位**小写**十六进制（缓存文件名、dat 前缀都用这个口径）。 */
export const MD5_RE = new RegExp('^' + MD5_SEGMENT + '$')

/** 整串校验：32 位十六进制，大小写都认（读用户可见文本时用）。 */
export const MD5_RE_LOOSE = new RegExp('^' + MD5_SEGMENT + '$', 'i')

/** 抽取用：在一串文本里找**第一个** 32 位十六进制段（不带锚，大小写敏感 = 历史口径）。 */
export const MD5_FIND_RE = new RegExp(MD5_SEGMENT)

/**
 * 是否是一个可以直接当缓存文件名用的 md5。
 * @param v - 待判定的串（不做 trim：首尾空白本身就是「不是 md5」）。
 */
export function isMd5(v: string): boolean {
  return MD5_RE.test(v)
}

/** 同上，但允许大写（微信侧存的是小写，所以拿到之后仍要 `toLowerCase()`）。 */
export function isMd5Loose(v: string): boolean {
  return MD5_RE_LOOSE.test(v)
}
