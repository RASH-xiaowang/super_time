/**
 * 分段发送时每段的字数上限。
 *
 * 取 **30**（2026-10-17 用户要求「每次回复不能超过 30 字」）：微信聊天里一条消息
 * 超过一屏就要滚动，而「像人连发几条」的节奏本来就是短句。30 字约等于一句口语
 * （「明天那个方案能出个初稿吗？」= 14 字），够说清一件事。
 *
 * ⚠️ 这个值同时写进了默认提示词（「每条不超过 30 字」）—— 改这里要同步改提示词，
 * 否则模型按旧字数写、切段按新字数切，会出现「一条被切成半句话」。
 */
export const CLAWBOT_REPLY_CHUNK_CHARS = 30

/**
 * 硬切一段超限文本（模块级：让 `splitReplyText` 留在棘轮线内）。
 *
 * ## 为什么不能纯按字数切（2026-10-17 真机实测）
 *
 * 30 字上限下，「你说的那个方案，我这边没查到相关内容，出不出得来初稿我真不清楚。」
 * （32 字）会被切成 `…我真不清` + `楚。` —— **「楚。」单独成一条**，读起来像乱码。
 *
 * 改进：优先在**次级标点**（逗号 / 顿号 / 冒号 / 分号）处切，找不到才纯按字数。
 * 这样切出来的是「半句 + 半句」，而不是「半句 + 两个字」。
 *
 * @param s - 超限的文本（已 trim）。
 * @param cap - 每段字数上限。
 * @returns 切好的段（每段 ≤cap，拼回去等于原文）。
 */
function hardSplit(s: string, cap: number): string[] {
  const out: string[] = []
  let rest = s
  while (rest.length > cap) {
    // 在 cap 之内找**最后一个**次级标点（含标点本身）。
    const window = rest.slice(0, cap)
    const m = /[，、：；,;:][^，、：；,;:]*$/.exec(window)
    // 切点：标点之后（标点跟着前一段走）。太靠前（<cap/2）就不值得切，退回纯字数切。
    const cut = m !== null && m.index >= Math.floor(cap / 2) ? m.index + 1 : cap
    out.push(rest.slice(0, cut))
    rest = rest.slice(cut)
  }
  if (rest !== '') out.push(rest)
  return out
}

/**
 * 把一段长回复切成多条（按段落优先，段落太长再按句子切）。
 *
 * 切法（顺序即优先级）：
 *   ① 先按**空行**切段（模型被要求「按语义分段，段间空一行」）；
 *   ② 单段仍超限 ⇒ 按**句末标点**（。！？；）切；
 *   ③ 单句仍超限 ⇒ 按**次级标点**（，、：；）切，再不行才纯按字数硬切。
 *
 * 为什么不用「按固定字数切」：那会把一句话拦腰截断，读起来像两条不相干的消息。
 * @param text - 完整回复正文。
 * @param limit - 每段字数上限（缺省 {@link CLAWBOT_REPLY_CHUNK_CHARS}）。
 * @returns 分段数组（至少一段；空输入返回空数组）。
 */
export function splitReplyText(text: string, limit: number = CLAWBOT_REPLY_CHUNK_CHARS): string[] {
  const trimmed = text.trim()
  if (trimmed === '') return []
  const cap = Math.max(Math.floor(limit), 1)
  if (trimmed.length <= cap) return [trimmed]

  const out: string[] = []
  // ① 按空行切段（保留段内换行）。
  for (const para of trimmed.split(/\n\s*\n/)) {
    const p = para.trim()
    if (p === '') continue
    if (p.length <= cap) { out.push(p); continue }
    // ② 段落太长 ⇒ 按句末标点切（标点跟着前一句走）。
    let buf = ''
    for (const sentence of p.split(/(?<=[。！？；!?;])/)) {
      const s = sentence.trim()
      if (s === '') continue
      if (buf !== '' && buf.length + s.length > cap) { out.push(buf); buf = '' }
      // ③ 单句仍超限 ⇒ 按次级标点切，再不行才纯按字数（罕见）。
      if (s.length > cap) {
        if (buf !== '') { out.push(buf); buf = '' }
        for (const piece of hardSplit(s, cap)) out.push(piece)
        continue
      }
      buf += s
    }
    if (buf !== '') out.push(buf)
  }
  return out.length > 0 ? out : [trimmed]
}
