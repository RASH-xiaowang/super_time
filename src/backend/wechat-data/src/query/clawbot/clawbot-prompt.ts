/**
 * ClawBot 自动回复的**默认系统提示词**（拟人化，2026-10-17）。
 *
 * ## 为什么要有它
 *
 * 自动回复此前**没有系统提示词** —— 它直接复用「微信问答」那套（「你是用户微信聊天记录里的
 * 问答助手……每句事实后面用 [n] 标注来源」）。那套是给**检索问答**写的：用户问一句、
 * 系统答一句、还要标引用角标。而自动回复是**在微信里跟人聊天**，用户看到的是：
 *
 *   · 报告腔（「综上所述」「根据数据分析」「经梳理」）；
 *   · 引用角标（`[1]`）—— 微信里没有角标可点，看着像乱码；
 *   · 生硬的「本机记录里没有检索到与这个问题相关的原文」；
 *   · 一句话答完就没了，不像人在聊天。
 *
 * ## 这套提示词要解决的四件事
 *
 * ① **像人**：口语化、有温度、可以寒暄，不要客服腔也不要报告腔；
 * ② **合理**：不编造（知识库里没有就说没有）、不装懂、不确定就说不确定；
 * ③ **长度合适**：微信聊天不该一次甩几千字，能一句说清就一句；
 * ④ **可分段**：内容确实长时按语义分段（配合 `splitReply` 逐条发出）。
 *
 * ## 与「检索问答」提示词的关系
 *
 * 两者**刻意分开**：检索问答要引用角标（界面上可点、可核对），自动回复不要
 * （微信里没有那个 UI）。所以自动回复走 `systemPromptOverride` 覆盖系统提示词，
 * 而**用户消息里的检索材料与规则仍然照旧**（那部分保证「不编造」的底线）。
 *
 * @module query/clawbot/clawbot-prompt
 */

