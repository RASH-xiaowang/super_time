/**
 * 连线预算（**建模层与绘制层共用同一定义**）。
 *
 * 为什么单独一个文件：额度原本只写在 `graph-canvas.ts` 里（未导出），而建模层
 * `graph-model.ts` 用的是**硬编码 6000** —— 于是「这一帧能画多少条」有两个互相不知道的答案。
 * 后果在审计里量化过：`edgeBudget` 被实际边数夹住时，建模层以为还有 6000 的额度，而密度上限
 * 只有 `nodeCount × EDGES_PER_NODE`（真机默认视图 251 节点 → 1255），多出来的边**一定画不出来**，
 * 用户看到的就是「模型里有、图上没有」。现在两层 import 同一个 `edgeBudget` / `edgeHeadroom`，
 * 任何一侧调常量，另一侧立刻跟着变，不会再各算一套。
 *
 * 硬编码 6000 的**残余**（真机全量视图实测，见 memory 2026-09-17）：建模层最后仍写
 * `derived.slice(0, 6000 - intimacy.length)`，把「亲密度 + 共同群 + 推断层」**一起**夹在 6000。
 * 而那一帧的密度上限是 `2606 × 5 = 13030` —— 于是有 **7030 条可以画、却没有生成的额度**，
 * 首字层（最后一批 push 的边）就是被这道切片整批切掉的（实测 +0 条）。
 * 现在这个数改成有名字的 `OBSERVED_EDGE_CAP`，且**只夹观测层**：
 *   观测层 = 亲密度 + 共同群/成员 → 夹在 `min(OBSERVED_EDGE_CAP, edgeDensityCap(n))`；
 *   推断层 = 同备注编号 + 首字 → 只用 `edgeHeadroom()` 问「还剩多少」，接在观测层之后。
 * 由此得到一条可断言的不变量：**模型边总数 ≤ 密度上限 = 绘制层额度 ⇒ 模型里的边一条都不会被裁掉**。
 *
 * 「真实观测到的关系」与「推断出来的关系」用不同额度：
 *   - 观测层（亲密度 / 共同群）—— 有多少画多少（只受总额度约束）；
 *   - 推断层（同备注编号 / 首字）—— 先用 `edgeHeadroom()` 问「还能加几条」，再决定生成多少，
 *     免得把自己推断出来的边画满，却把真实关系挤掉。
 */

/**
 * 连线预算的下限：**图不大时，真实存在的边一条都不许少**。
 *
 * 为什么不是 180（原值，实测被证伪）：它是「小图（几十个节点）也要画得下这批边」这条
 * 意图拍下来的一个整数，但**没有覆盖「一个群本身就是完全图」这种正常情况**。反例：
 *   20 个节点、其中 19 人同处一个群 → 亲密度 19 条 + 同群 C(19,2)=171 条 = **190 条**，
 *   而额度 `max(180, 20×5=100) = 180` —— **差 10 条**，于是「19 人同群」在模型里被切成 161 对。
 * （改前这道差额不体现在模型上 —— 模型照样给 190 条 —— 而是被绘制层悄悄裁掉，用户看到的
 * 同样是「同群的人之间少了几条线」，只是错在另一层。）
 *
 * 为什么也不是随便更大的数：它不能越过**群组网络**那档的实测定档。真机群组网络
 * `691 条 / 65 节点 = 10.63 条/节点`，那才是真的糊、必须按权重截断，其额度是 `65×5 = 325`。
 * 下限一旦 ≥ 325 就会把这档也放开（325 → 691），等于把「大群网络要截断」这个决定推翻。
 *
 * 所以取值被两条真机约束夹在 **[190, 325)** 之间，取中间的整数 300（= C(25,2)：一个 25 人
 * 的群能整组画全，而 25 人是很常见的群规模）。真机各路视图都在这条下限之上
 * （默认 251 节点 → 1255、群组网络 65 节点 → 325），所以**改这个数不影响任何真实视图的观感**，
 * 只是把「小图上把真实关系画全」补回来。
 */
export const MIN_EDGE_BUDGET = 300

/**
 * 观测层（亲密度 + 共同群/成员）的显示上限。
 *
 * 为什么需要它：观测层是「有多少画多少」的，而**共同群点对是 O(G²) 的** —— 真机全量视图
 * 实测原始共同群点对 **34953 条**（2605 个节点），远超任何合理的渲染量。到这一步按权重降序
 * 保留最强的那些（`buildGraph` 里 `edges` 已按 weight 降序），所以被丢掉的都是「只共处过
 * 1 个群」的弱关系。
 *
 * 为什么是 6000：这就是原来那道硬编码切片的数值，**行为刻意保持不变** —— 唯一改变的是它
 * 从「夹住全部边」改成「只夹观测层」，从而把 `edgeDensityCap` 与它之间的差额留给推断层。
 * 数值本身不是本次调的（它原本就没被论证过），而是「先冻结现状、再把被它误伤的额度还回去」。
 */
export const OBSERVED_EDGE_CAP = 6000

/**
 * 每个节点允许画多少条连线。
 *
 * 为什么是 5（**实测定档，不是拍的**）：真机数据里默认好友视图是 998 条边 / 251 个节点
 * = **3.98 条/节点**，群组网络是 691 / 65 = 10.63 条/节点。取 5 使**默认视图的同群关系
 * 一条不缺**（3.98 < 5，留一点余量给关系更密的账号），同时仍然对群组网络那种
 * 「一个节点平均挂 10 条线」的密度按权重截断 —— 那才是真的糊。
 *
 * 改前是 0.9，后果不是「少画几条装饰线」：同群关系（`kind: 'common'`）是好友视图里
 * **唯一的**人际关系边，0.9 的额度只能画下 748 条中的 226 条 —— 实测 251 个人里
 * **103 个**的同群伙伴在画面上一条线都没有，用户看到的正是「同群成员之间没有链接」。
 * 「连线太多会糊」这个担心对小图不成立：3.98 条/节点的图平均度只有 8，远不到糊的程度。
 */
export const EDGES_PER_NODE = 5

/**
 * 绝对上限。比例额度在节点数很大时会失效（10000 节点 × 5 = 5 万条线没法看，
 * 逐帧描边的成本也开始可见），所以再加一道与规模无关的天花板。
 * 到了这一步按 kind 分桶 + 权重降序截断是合理的，骨架仍然被无条件保底。
 */
export const MAX_EDGE_BUDGET = 24000

/**
 * **密度上限**：这一帧到底能容纳多少条边 —— 绘制层与建模层的**单一口径**。
 *
 * `min(MAX_EDGE_BUDGET, max(MIN_EDGE_BUDGET, nodeCount × EDGES_PER_NODE))`
 *
 * 为什么单独抽出来：这个式子原本在 `edgeHeadroom` 里内联了一份、在 `edgeBudget` 里
 * 又以「三个下限取 max」的形式散着写了一份 —— 而它其实是**绘制层这一帧到底能容纳多少条边**
 * 这一个问题的同一个答案。抽成一个函数之后，建模层要问「还能加几条」（`edgeHeadroom`）、
 * 要问「观测层该夹在哪」（`buildGraph` 里的 `observedCap`）、绘制层要问「画多少」（`edgeBudget`），
 * 三处都指向这里，不会再各自演化出第二套数字。
 *
 * 注意它**不含** `backbone`：骨架是「每个有边节点一条」的连通性下界，条数天然 ≤ 节点数，
 * 而节点数本身 ≤ 这个下限（`n×5 ≥ n`，且 `n ≤ 300` 时由 `MIN_EDGE_BUDGET` 兜住），
 * 所以不含它偏保守、不会高估余量。
 * @param nodeCount - 节点数。
 * @returns 这一帧能容纳的边数上限。
 */
/** 把 `NaN` / `Infinity` / 负数一律折成 0。额度算成 `NaN` 会顺着 `slice` 与比较符**静默**传播
 *  （`NaN` 做数组下标等于 0，进 `sort` 比较器则顺序未定义），界面不报错、只是画错，所以入口夹一次。 */
function nonNegative(x: number): number {
  return Number.isFinite(x) ? Math.max(0, x) : 0
}

export function edgeDensityCap(nodeCount: number): number {
  const byDensity = Math.round(nonNegative(nodeCount) * EDGES_PER_NODE)
  return Math.min(MAX_EDGE_BUDGET, Math.max(MIN_EDGE_BUDGET, byDensity))
}

/**
 * 连线预算：节点越多，只画权重最高的那些（改前 ECharts 版同口径，避免大图被线糊住）。
 *
 * 外层再夹一次 `edgeCount`：改前的写法是 `Math.max(下限, Math.min(edgeCount, …))`，边很少时
 * 会返回一个比实际边数还大的「预算」（例如只有 5 条边却返回下限那个数）。`slice` 之下无害，但会让
 * 任何拿它做循环上界、或打印「画了多少条」的地方对不上 —— 预算就该不超过可用量。
 *
 * 下限取最大值，各自守一件事（前两条已含在 `edgeDensityCap` 里，见它的文档）：
 *   - `MIN_EDGE_BUDGET`：图不大时真实存在的边一条都不许少（见该常量的推导）；
 *   - `nodeCount × EDGES_PER_NODE`：按密度给的额度，决定默认视图能不能画全同群关系；
 *   - `backbone`：**连通性骨架**先于预算（见 `connectivityBackbone`）——它被裁掉就等于把
 *     真实存在的关系画没了，所以它是一条**下限**而不是额外额度（不能写成 `cap + backbone`）。
 * @param nodeCount - 节点数（渲染中的节点，不含只出现在边表里的 id）。
 * @param edgeCount - 实际边数。
 * @param backbone - 骨架条数；缺省 0（保持「纯预算」语义，便于单独断言预算曲线）。
 * @returns 实际绘制的边数上限。
 */
export function edgeBudget(nodeCount: number, edgeCount: number, backbone = 0): number {
  // backbone 也是一条**下限**（不是 cap + backbone）：骨架被裁掉就等于把真实关系画没了
  const floor = Math.max(edgeDensityCap(nodeCount), nonNegative(backbone))
  return Math.min(nonNegative(edgeCount), MAX_EDGE_BUDGET, floor)
}

/**
 * 「还能再加多少条」—— 在不挤掉任何**已有**边的前提下，推断层可以新增的条数。
 *
 * 与 `edgeBudget` 的区别：`edgeBudget` 是**总额度**（已画的 + 还能画的），而这里问的是**增量**。
 * 推断层必须用这个数来限制自己生成多少条，否则后果实测过：
 * `graph-model` 生成「同班级完全图」时，模型边从 1031 涨到 1600，而额度仍是 1255 →
 * `selectEdges` 的分桶截断把**共同群边从 748 压到 503**（牺牲 245 条真实观测到的关系，
 * 去换 502 条自己推断出来的边）。现在改成「按余量截断」后：班级边 257 条、共同群边 748 条，
 * **一条不牺牲**。
 *
 * 只按 `edgeDensityCap()` 算（不含 backbone）：backbone 是「每个有边节点一条」的连通性下界，
 * 条数天然 ≤ 节点数，而节点数本身 ≤ 这个下限，所以忽略它偏保守、不会高估余量。
 * @param nodeCount - 节点数。
 * @param usedEdges - **已经真正产出**的边数（夹过的观测层 + 更优先的推断层）。注意是「产出」
 *   而不是「原始」：观测层被 `OBSERVED_EDGE_CAP` 夹掉的部分不占额度，否则那道上限会连着
 *   把推断层一起饿死（真机全量视图就是这个后果：原始观测 37558 条 → 余量 0 → 首字层 +0）。
 * @returns 可新增的条数（≥0）。
 */
export function edgeHeadroom(nodeCount: number, usedEdges: number): number {
  return Math.max(0, edgeDensityCap(nodeCount) - nonNegative(usedEdges))
}
